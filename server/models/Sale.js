/**
 * server/models/Sale.js
 * ---------------------
 * The sales collection — UC5, "Record a sale".
 *
 * One document per package sold to a customer. This is the electronic version
 * of the paper card in Fig. 3 of the requirements: it records what was bought,
 * what was paid, and the window the purchase is good for.
 *
 * The one decision worth defending here is that a sale SNAPSHOTS the package
 * rather than only pointing at it. The price, the class count and the
 * unlimited flag are copied onto the sale at the moment it is recorded.
 *
 * Why: a package is editable (the studio raises prices), and a sale is a
 * historical fact. If the sale only held a packageId, raising the price of
 * the 10 Class Pass would silently rewrite every sale ever made of it, and
 * the package sales report in UC7 would report revenue the studio never took.
 * The duplication is deliberate, and the field comments say so.
 */

import mongoose from 'mongoose';

/**
 * How the customer paid.
 *
 * The specification says "mode of payment" without listing the options, so
 * these are an assumption taken from the studio's own attendance sheet
 * (Fig. 4), which records cash, cheque and card. Documented in the report.
 */
export const PAYMENT_MODES = ['Cash', 'Card', 'Check'];

const saleSchema = new mongoose.Schema(
  {
    // "S00001". Generated by the controller, never typed in.
    saleId: {
      type: String,
      required: true,
      unique: true,
      immutable: true,
    },

    // Who bought it, by readable ID. Checked against the customers
    // collection by the controller, since MongoDB enforces no references.
    customerId: {
      type: String,
      required: [true, 'Please choose a customer.'],
      uppercase: true,
      trim: true,
    },

    // What they bought, by readable ID.
    packageId: {
      type: String,
      required: [true, 'Please choose a package.'],
      uppercase: true,
      trim: true,
    },

    // Copied from the package at the time of sale, for the reason in the file
    // header: a sale must keep saying what was actually bought.
    packageName: {
      type: String,
      required: true,
    },

    /**
     * How many classes this sale added to the customer's balance.
     * `null` for an unlimited package, which is entitlement by date rather
     * than by count (design decision 4).
     */
    classesPurchased: {
      type: Number,
      default: null,
    },

    unlimited: {
      type: Boolean,
      required: true,
      default: false,
    },

    /**
     * Which classes this purchase admits its holder to, copied from the
     * package. A 'General' purchase covers General classes; a 'Special' one
     * covers only classes marked Special.
     *
     * Snapshotted for the same reason as the rest: UC6 asks "was this
     * customer entitled to be in that class on that date", and the answer
     * must not change because the package was edited afterwards.
     */
    classType: {
      type: String,
      required: [true, 'Class type is required.'],
      enum: {
        values: ['General', 'Special'],
        message: 'Class type must be either General or Special.',
      },
    },

    /**
     * What the customer actually paid.
     *
     * UC5 step 4 requires this to match the package rate, which the
     * controller checks. It is still stored separately rather than read back
     * off the package, because the amount taken is the fact the studio's
     * books care about.
     */
    amountPaid: {
      type: Number,
      required: [true, 'Amount paid is required.'],
      min: [0, 'Amount paid cannot be negative.'],
    },

    paymentMode: {
      type: String,
      required: [true, 'Please choose a mode of payment.'],
      enum: {
        values: PAYMENT_MODES,
        message: `Mode of payment must be one of: ${PAYMENT_MODES.join(', ')}.`,
      },
    },

    // UC5 step 4: "Date and time are current". A full timestamp, not a date:
    // the studio's card records when a package was bought, and two sales on
    // one day need an order.
    paidAt: {
      type: Date,
      required: [true, 'Date and time of payment are required.'],
    },

    // UC5: "Validity start and end date". The window this purchase can be
    // used in, which UC6 checks when an unlimited customer checks in.
    validFrom: {
      type: Date,
      required: [true, 'Validity start date is required.'],
    },

    validTo: {
      type: Date,
      required: [true, 'Validity end date is required.'],
      validate: {
        validator: function (value) {
          return !this.validFrom || value > this.validFrom;
        },
        message: 'Validity end date must be after the start date.',
      },
    },
  },
  {
    timestamps: true,
  }
);

/**
 * Is this purchase usable today? True when today falls inside the validity
 * window. UC6 uses it to decide whether an unlimited customer may check in,
 * and UC7 uses it to label a customer's packages active, future or expired.
 */
saleSchema.virtual('isActive').get(function () {
  const now = new Date();
  return this.validFrom <= now && this.validTo >= now;
});

/** 'active' | 'future' | 'expired' — the three labels UC7's report asks for. */
saleSchema.virtual('status').get(function () {
  const now = new Date();
  if (this.validFrom > now) return 'future';
  if (this.validTo < now) return 'expired';
  return 'active';
});

saleSchema.set('toJSON', { virtuals: true });
saleSchema.set('toObject', { virtuals: true });

// A customer's purchase history is read on every attendance check and in two
// of the UC7 reports, so it is indexed; paidAt is the sort order for the
// sales report.
saleSchema.index({ customerId: 1, validTo: -1 });
saleSchema.index({ paidAt: -1 });

export default mongoose.model('Sale', saleSchema);
