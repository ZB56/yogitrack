/**
 * server/models/Class.js
 * ----------------------
 * The classes collection — UC2, "Add a class".
 *
 * A class here is a WEEKLY SLOT in the published schedule ("Chair Yoga,
 * Tuesdays at 9:00, with Maya"), not a single dated occurrence. That follows
 * the requirements: Fig. 1 is a weekly timetable, and UC2 collects a day and a
 * time rather than a date. A particular Tuesday only becomes a record when
 * attendance is taken for it (UC6), which is also how the studio's paper
 * attendance sheets work.
 *
 * The ID prefix is L, for "cLass": C was already taken by customer, and UC1
 * and UC4 make the point that a reader should be able to tell the kinds of ID
 * apart at a glance.
 */

import mongoose from 'mongoose';

// Monday first, matching the studio's printed timetable. The order matters:
// DAYS.indexOf(day) is what sorts the schedule and what "the next day" means
// when suggesting alternative slots.
export const DAYS = [
  'Monday',
  'Tuesday',
  'Wednesday',
  'Thursday',
  'Friday',
  'Saturday',
  'Sunday',
];

// 24-hour "HH:MM". Stored as text rather than a Date because a weekly slot has
// no date attached, and because "09:00" sorts and compares correctly as a
// string while a Date would drag a timezone into a value that has none.
const TIME_PATTERN = /^([01]\d|2[0-3]):([0-5]\d)$/;

// What a class lasts when nobody says otherwise. The specification never
// states a class length, and the conflict check in UC2 cannot work without
// one, so 60 minutes is the documented assumption (design decision 5). It is
// a field rather than a constant so the studio's longer workshops can say so.
export const DEFAULT_DURATION_MINUTES = 60;

const classSchema = new mongoose.Schema(
  {
    // "L00001". Generated by the controller, never typed by the manager.
    classId: {
      type: String,
      required: true,
      unique: true,
      immutable: true,
    },

    /**
     * Which instructor leads it, by their readable ID ("I00001").
     *
     * The readable ID rather than the MongoDB _id, so that a class document
     * is legible on its own and matches what the manager sees on screen. The
     * controller checks that the instructor exists before saving, because
     * MongoDB does not enforce references between collections.
     */
    instructorId: {
      type: String,
      required: [true, 'Please choose an instructor.'],
      uppercase: true,
      trim: true,
    },

    day: {
      type: String,
      required: [true, 'Please choose a day.'],
      enum: {
        values: DAYS,
        message: 'Day must be a day of the week.',
      },
    },

    time: {
      type: String,
      required: [true, 'Start time is required.'],
      trim: true,
      match: [TIME_PATTERN, 'Start time must be a 24-hour time such as 09:00.'],
    },

    durationMinutes: {
      type: Number,
      required: true,
      default: DEFAULT_DURATION_MINUTES,
      min: [15, 'A class must last at least 15 minutes.'],
      max: [240, 'A class cannot last longer than four hours.'],
    },

    /**
     * General or Special, the same two values a package carries.
     *
     * This is the link between what a customer bought and what they may
     * attend: a 'General' package admits its holder to any General class,
     * while a Special package (e.g. Yoga with Weights) admits them only to
     * classes marked Special. UC6 enforces that when taking attendance.
     */
    classType: {
      type: String,
      required: [true, 'Please choose a class type.'],
      enum: {
        values: ['General', 'Special'],
        message: 'Class type must be either General or Special.',
      },
    },

    /**
     * What the instructor is paid for leading this class, in US dollars.
     * UC7's teacher payment report multiplies this by the number of classes
     * actually held, which is why it belongs to the class and not to the
     * instructor: a studio pays more for a workshop than for a drop-in hour.
     */
    payRate: {
      type: Number,
      required: [true, 'Pay rate is required.'],
      min: [0, 'Pay rate cannot be negative.'],
    },

    // Consistent with the other collections: a class with attendance recorded
    // against it must not simply vanish (design decision 9).
    active: {
      type: Boolean,
      default: true,
    },
  },
  {
    timestamps: true,
  }
);

/**
 * Convert "HH:MM" to minutes since midnight: "09:30" -> 570.
 *
 * Comparing times as numbers is what makes the overlap test in UC2 a pair of
 * ordinary inequalities. Exported because the controller needs the same
 * conversion when testing a proposed slot that is not a document yet.
 *
 * @param {string} time - 24-hour "HH:MM"
 * @returns {number} minutes since 00:00
 */
export function timeToMinutes(time) {
  const [hours, minutes] = time.split(':').map(Number);
  return hours * 60 + minutes;
}

/**
 * The inverse: 570 -> "09:30". Used when proposing alternative slots.
 *
 * @param {number} totalMinutes
 * @returns {string} 24-hour "HH:MM"
 */
export function minutesToTime(totalMinutes) {
  const hours = Math.floor(totalMinutes / 60);
  const minutes = totalMinutes % 60;
  return `${String(hours).padStart(2, '0')}:${String(minutes).padStart(2, '0')}`;
}

/**
 * Does a proposed slot clash with this class?
 *
 * UC2 step 2: only one class can be held at any time. Two slots clash when
 * they fall on the same day and their time ranges overlap. The test is the
 * standard one for intervals: A starts before B ends, AND B starts before A
 * ends. Touching ranges do not count, so a 9:00 class of 60 minutes leaves
 * 10:00 free.
 *
 * @param {{day: string, time: string, durationMinutes: number}} slot
 * @returns {boolean}
 */
classSchema.methods.clashesWith = function clashesWith(slot) {
  if (this.day !== slot.day) return false;

  const thisStart = timeToMinutes(this.time);
  const thisEnd = thisStart + this.durationMinutes;

  const otherStart = timeToMinutes(slot.time);
  const otherEnd = otherStart + (slot.durationMinutes || DEFAULT_DURATION_MINUTES);

  return thisStart < otherEnd && otherStart < thisEnd;
};

/** "Tuesday 09:00" — how the slot reads in a message or a confirmation. */
classSchema.virtual('slotLabel').get(function () {
  return `${this.day} ${this.time}`;
});

/** When the class finishes, derived so it can never disagree with the start. */
classSchema.virtual('endTime').get(function () {
  return minutesToTime(timeToMinutes(this.time) + this.durationMinutes);
});

classSchema.set('toJSON', { virtuals: true });
classSchema.set('toObject', { virtuals: true });

// The conflict check queries by day on every save, and UC6 lists an
// instructor's own classes, so both are indexed.
classSchema.index({ day: 1, time: 1 });
classSchema.index({ instructorId: 1 });

export default mongoose.model('Class', classSchema);
